// POST /api/account  { action: "signup" | "login" | "logout" | "me" }
import { route, json, readBody, HttpError } from "../lib/http.js";
import { currentUser, hashPassword, verifyPassword, sessionCookie, clearCookie, normalizeEmail, userKey, limit, saveUser } from "../lib/auth.js";
import { refreshSubscription, PLAN } from "../lib/billing.js";
import { db } from "../lib/store.js";

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
const publicPlan = {
  name: PLAN.name, cents: PLAN.cents, currency: PLAN.currency, trialDays: PLAN.trialDays,
  // Plus can be sold only once payments and the AI tutor are both configured.
  plusAvailable: !!process.env.STRIPE_SECRET_KEY && !!process.env.ANTHROPIC_API_KEY && process.env.PLUS_ENABLED !== "0",
  // Languages without hand-written lessons are generated by Claude on first use, only when enabled.
  generateLessons: process.env.GENERATE_LESSONS === "1",
};

async function me(user) {
  if (!user) return { user: null, plan: publicPlan };
  const subscribed = await refreshSubscription(user);
  return { user: { email: user.email, subscribed }, plan: publicPlan };
}

export const POST = route(async (request) => {
  const body = await readBody(request);
  const ip = request.headers.get("x-forwarded-for")?.split(",")[0].trim() || "local";

  switch (body.action) {
    case "me":
      return json(await me(await currentUser(request)));

    case "signup": {
      const email = normalizeEmail(body.email);
      const password = String(body.password || "");
      if (!EMAIL_RE.test(email)) throw new HttpError(400, "That email doesn't look right.");
      if (password.length < 8) throw new HttpError(400, "Use at least 8 characters for your password.");
      await limit(`signup:${ip}`, 10, 3600, "Too many sign-ups from here. Try again later.");
      const created = await db().set(userKey(email), { passwordHash: await hashPassword(password), createdAt: Date.now() }, { nx: true });
      if (!created) throw new HttpError(409, "There's already an account with that email. Log in instead.");
      return json(await me({ email, ...(await db().get(userKey(email))) }), 200, { "Set-Cookie": sessionCookie(email) });
    }

    case "login": {
      const email = normalizeEmail(body.email);
      await limit(`login:${email}`, 10, 900, "Too many tries. Wait 15 minutes and try again.");
      const user = await db().get(userKey(email));
      const ok = user && (await verifyPassword(String(body.password || ""), user.passwordHash));
      if (!ok) throw new HttpError(401, "Wrong email or password.");
      return json(await me({ email, ...user }), 200, { "Set-Cookie": sessionCookie(email) });
    }

    case "logout":
      return json({ ok: true }, 200, { "Set-Cookie": clearCookie() });

    case "delete": {
      const user = await currentUser(request);
      if (!user) throw new HttpError(401, "Please log in.", "login");
      if (user.subscribed) throw new HttpError(400, "Cancel your subscription first (Manage subscription), then delete your account.");
      await db().del(userKey(user.email));
      await db().del(`progress:${user.email}`);
      return json({ ok: true }, 200, { "Set-Cookie": clearCookie() });
    }

    default:
      throw new HttpError(400, "Unknown action.");
  }
});
